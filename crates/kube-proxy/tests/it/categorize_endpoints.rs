/// (endpoint, zoneHints, nodeHints, ready, serving, terminating, isLocal)
type Ep = (
    &'static str,
    &'static [&'static str],
    &'static [&'static str],
    bool,
    bool,
    bool,
    bool,
);

struct Case {
    name: &'static str,
    prefer: bool,
    node: &'static str,
    zone: Option<&'static str>,
    itp: bool,
    etp: bool,
    node_port: bool,
    endpoints: &'static [Ep],
    cluster: &'static [&'static str],
    local: &'static [&'static str],
    all: &'static [&'static str],
    only_remote: bool,
}

fn info(e: &Ep) -> EndpointInfo {
    let (addr, port) = e.0.rsplit_once(':').unwrap();
    EndpointInfo {
        ip: addr.to_string(),
        port: port.parse().unwrap(),
        is_local: e.6,
        ready: e.3,
        serving: e.4,
        terminating: e.5,
        zone_hints: e.1.iter().map(|s| s.to_string()).collect(),
        node_hints: e.2.iter().map(|s| s.to_string()).collect(),
    }
}

fn svc(itp: bool, etp: bool, node_port: bool) -> BaseServicePortInfo {
    BaseServicePortInfo {
        cluster_ip: "10.96.0.1".parse().unwrap(),
        port: 80,
        protocol: "TCP".into(),
        node_port: if node_port { 8080 } else { 0 },
        load_balancer_vips: vec![],
        session_affinity_type: "None".into(),
        sticky_max_age_seconds: 0,
        external_ips: vec![],
        load_balancer_source_ranges: vec![],
        health_check_node_port: 0,
        external_policy_local: etp,
        internal_policy_local: itp,
    }
}

fn set(v: &[EndpointInfo]) -> BTreeSet<String> {
    v.iter().map(|e| e.endpoint()).collect()
}

fn expect(v: &[&str]) -> BTreeSet<String> {
    v.iter().map(|s| s.to_string()).collect()
}

#[test]
fn categorize_endpoints_upstream_table() {
    for c in CASES {
        let endpoints: Vec<EndpointInfo> = c.endpoints.iter().map(info).collect();
        let mut labels = BTreeMap::new();
        if let Some(z) = c.zone {
            labels.insert(LABEL_TOPOLOGY_ZONE.to_string(), z.to_string());
        }
        let got = categorize_endpoints(
            &endpoints,
            &svc(c.itp, c.etp, c.node_port),
            c.node,
            &labels,
            c.prefer,
        );
        assert_eq!(set(&got.cluster), expect(c.cluster), "{}: cluster", c.name);
        assert_eq!(set(&got.local), expect(c.local), "{}: local", c.name);
        // The upstream harness derives the expected `all` from cluster/local.
        let want_all = if !c.cluster.is_empty() && c.local.is_empty() {
            expect(c.cluster)
        } else if !c.local.is_empty() && c.cluster.is_empty() {
            expect(c.local)
        } else {
            expect(c.all)
        };
        assert_eq!(set(&got.all_reachable), want_all, "{}: all", c.name);
        assert_eq!(
            got.has_any_endpoints,
            !want_all.is_empty() || c.only_remote,
            "{}: hasAnyEndpoints",
            c.name
        );
    }
}

